#!/usr/bin/env python3
"""Generate AutoMask-v5 experiment plans and safe launcher templates; never train."""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Mapping

ROOT = Path(__file__).resolve().parents[3]
OUTPUT_ROOT = ROOT / "experiments/counterfactual_cot/outputs"
V5_MARKERS = ("automask-v5", "automask_v5", "auto_mask_v5", "gold40_automask_v5")


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _rows(path: Path) -> list[dict[str, Any]]:
    text = path.read_text(encoding="utf-8").strip()
    if not text:
        raise ValueError(f"AutoMask-v5 manifest is empty: {path}")
    if path.suffix.lower() == ".json":
        value = json.loads(text)
        value = value.get("records") if isinstance(value, dict) and isinstance(value.get("records"), list) else value
    else:
        value = [json.loads(line) for line in text.splitlines() if line.strip()]
    if not isinstance(value, list) or not all(isinstance(row, dict) for row in value):
        raise ValueError(f"{path} must be a JSON array/records list or JSONL objects")
    return value


def _mask_mapping(row: Mapping[str, Any]) -> Mapping[str, Any] | None:
    for key in ("automatic_difference_mask", "auto_mask_v5", "automask_v5", "auto_mask", "automask", "mask"):
        if isinstance(row.get(key), Mapping):
            return row[key]
    return None


def _is_v5(row: Mapping[str, Any]) -> bool:
    mask = _mask_mapping(row)
    if mask is None and "auto_mask_path" not in row:
        return False
    marker_source = mask or row
    marker = " ".join(str(value).lower() for value in (row.get("schema_version"), row.get("mask_generator"), row.get("mask_method"), marker_source.get("schema_version"), marker_source.get("generator"), marker_source.get("method"), marker_source.get("version")) if value is not None)
    return any(token in marker for token in V5_MARKERS) or "auto_mask_v5" in row or "automask_v5" in row


def _has_mask_path(row: Mapping[str, Any]) -> bool:
    mask = _mask_mapping(row) or {}
    return any(isinstance(mask.get(key) or row.get(key), str) and (mask.get(key) or row.get(key)).strip() for key in ("auto_mask_path", "mask_path", "path", "image_path"))


def _validate(path: Path, role: str) -> dict[str, Any]:
    records = _rows(path)
    pair_ids: set[str] = set()
    scenes: set[str] = set()
    invalid: list[str] = []
    for index, row in enumerate(records, 1):
        pair_id = str(row.get("pair_id") or row.get("macro_pair_id") or "").strip()
        scene_id = str(row.get("source_scene_id") or "").strip()
        if not pair_id or not scene_id or not _is_v5(row) or not _has_mask_path(row):
            invalid.append(f"row={index}, pair_id={pair_id!r}, source_scene_id={scene_id!r}")
            continue
        if pair_id in pair_ids:
            invalid.append(f"duplicate pair_id={pair_id!r}")
        pair_ids.add(pair_id); scenes.add(scene_id)
    if invalid:
        raise ValueError(f"{role} must be an explicit AutoMask-v5 manifest with unique pair_id, source_scene_id, and automatic mask path; invalid examples: {invalid[:5]}")
    return {"path": str(path.resolve()), "sha256": _sha256(path), "records": len(records), "pair_ids": sorted(pair_ids), "source_scene_ids": sorted(scenes), "contract": "Each row identifies pair_id and source_scene_id and carries an explicit AutoMask-v5 automatic mask path; manual v4 reviewed-mask approval is not substituted."}


def _launcher(plan_sha: str, spec: Mapping[str, Any], train: Mapping[str, Any], evaluation: Mapping[str, Any]) -> str:
    header = f'''#!/usr/bin/env bash
# Generated by build_automask_v5_plan.py.
set -euo pipefail
PLAN_SHA256="{plan_sha}"
EXPERIMENT_ID="{spec["id"]}"
TRAIN_AUTO_MANIFEST="{train["path"]}"
EVAL_AUTO_MANIFEST="{evaluation["path"]}"
OUTPUT_DIR="{spec["output_dir"]}"
'''
    if spec["id"] != "automask_v5_main":
        return header + '''printf '%s\\n' "Refusing to launch $EXPERIMENT_ID (plan $PLAN_SHA256)."
printf '%s\\n' "AutoMask-v5 train manifest: $TRAIN_AUTO_MANIFEST"
printf '%s\\n' "AutoMask-v5 held-out manifest: $EVAL_AUTO_MANIFEST"
printf '%s\\n' "Requested output directory: $OUTPUT_DIR"
printf '%s\\n' "FAIL-FAST: no registered mask-free paired-v5 objective/trainer exists."
printf '%s\\n' "Do not replace this guard with a v4 or AutoMask-main torchrun command."
exit 2
'''
    return header + f'''ROOT="{ROOT}"
ENTRYPOINT="$ROOT/experiments/counterfactual_cot/gold40_automask_dual_target_cot1024_fsdp_v5/train.py"
MODEL_DIR="${{MODEL_DIR:-/dockerdata/niightli/BAGEL/models/BAGEL-7B-MoT}}"
GPU_IDS="${{GPU_IDS:-0,1}}"
STEPS="${{STEPS:-960}}"
export CUDA_VISIBLE_DEVICES="$GPU_IDS"
export PYTHONUNBUFFERED=1
export TOKENIZERS_PARALLELISM=false
export PYTORCH_CUDA_ALLOC_CONF="expandable_segments:True,max_split_size_mb:128"
export NCCL_ASYNC_ERROR_HANDLING=1
printf '%s\\n' "Launching $EXPERIMENT_ID with the registered AutoMask-v5 two-rank trainer (plan $PLAN_SHA256)."
printf '%s\\n' "Held-out AutoMask-v5 manifest is locked for evaluation and is not passed to training: $EVAL_AUTO_MANIFEST"
cd "$ROOT"
exec torchrun --standalone --nproc_per_node=2 "$ENTRYPOINT" \\
  --manifest "$TRAIN_AUTO_MANIFEST" \\
  --output-dir "$OUTPUT_DIR" \\
  --llm-path "$MODEL_DIR" \\
  --vae-path "$MODEL_DIR/ae.safetensors" \\
  --checkpoint-path "$MODEL_DIR/ema.safetensors" \\
  --steps "$STEPS" \\
  --lr 3e-5 \\
  --lora-r 8 \\
  --lora-alpha 16 \\
  --activation-checkpointing \\
  --checkpoint-every 10 \\
  --seed 1234 \\
  --variant automask_v5_main
'''


def _specs() -> list[dict[str, Any]]:
    mask_free_unavailable = "No registered trainer implements the paired-v5 mask-free objective; launcher intentionally exits before torchrun."
    common = {"heldout_protocol": "Use the locked held-out AutoMask-v5 manifest, matched generation seeds, a generation-result manifest, and a separate explicit automated-semantic-label manifest. Run audit_gold40_automask_v5.py for source/target accuracy, same-seed SwitchAcc, edit/outside MAE, and bootstrap CIs.", "evaluation_inputs": ["v5_auto_manifest", "generation_manifest", "automated_semantic_label_manifest"]}
    return [
        {"id": "automask_v5_main", "label": "AutoMask-v5 paired main", "input": "Paired AutoMask-v5 train manifest with automatic_difference_mask/automask regions consumed as the v5 region-supervision contract.", "training_difference": "Main method: retains source/target paired macro-steps and applies the AutoMask-v5 region objective. It must not claim human-reviewed v4 mask supervision.", "output_dir": str(OUTPUT_ROOT / "gold40_automask_v5" / "main"), "implementation": {"state": "implemented_training_only", "entrypoint": "experiments/counterfactual_cot/gold40_automask_dual_target_cot1024_fsdp_v5/train.py", "manifest_argument": "--manifest", "launcher_behavior": "torchrun --standalone --nproc_per_node=2; generator does not execute it", "evaluation_state": "audit tool implemented; generation/semantic-label production remains external"}, "evaluation": common},
        {"id": "paired_v5_mask_free", "label": "paired-v5 mask-free ablation", "input": "Same paired AutoMask-v5 train manifest, but the objective must explicitly ignore all automatic mask pixels while preserving every other v5 pairing, optimizer, and seed/noise setting.", "training_difference": "Ablates automatic region supervision only; it is not a different data split, independent-branch method, or v4 fallback.", "output_dir": str(OUTPUT_ROOT / "gold40_automask_v5" / "paired_mask_free"), "implementation": {"state": "unimplemented_fail_fast", "reason": mask_free_unavailable}, "evaluation": common},
    ]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--train-auto-manifest", required=True, type=Path)
    parser.add_argument("--eval-auto-manifest", required=True, type=Path)
    parser.add_argument("--output-dir", required=True, type=Path)
    parser.add_argument("--force", action="store_true", help="Replace generated plan/template files after reviewing their diff.")
    args = parser.parse_args()
    try:
        train_path, eval_path = args.train_auto_manifest.resolve(), args.eval_auto_manifest.resolve()
        if train_path == eval_path:
            raise ValueError("Train and held-out AutoMask-v5 manifests must be distinct")
        train, evaluation = _validate(train_path, "train"), _validate(eval_path, "evaluation")
        overlapping_scenes = sorted(set(train["source_scene_ids"]) & set(evaluation["source_scene_ids"]))
        if overlapping_scenes:
            raise ValueError(f"Train/evaluation source_scene_id leakage: {overlapping_scenes[:10]}")
        output_dir = args.output_dir.resolve(); plan_path = output_dir / "experimental_plan.json"; launcher_dir = output_dir / "launchers"
        if (plan_path.exists() or launcher_dir.exists()) and not args.force:
            raise ValueError(f"Refusing to overwrite generated artifacts in {output_dir}; use --force after auditing the diff")
        specs = _specs()
        plan = {"schema_version": "gold40_automask_v5_experiment_plan_v1", "created_at": _now(), "generator": str(Path(__file__).resolve()), "training_started": False, "train_auto_manifest": train, "eval_auto_manifest": evaluation, "source_scene_leakage_check": "passed", "global_contract": "The two variants share exact train/eval manifests and matched protocol. Semantic success is read only from a separate explicit automated-semantic-label manifest; AutoMask-v5 pixels produce edit/preservation diagnostics only.", "experiments": specs}
        serialized = json.dumps(plan, ensure_ascii=False, indent=2, sort_keys=True) + "\n"; plan_sha = hashlib.sha256(serialized.encode()).hexdigest()
        output_dir.mkdir(parents=True, exist_ok=True); plan_path.write_text(serialized, encoding="utf-8"); launcher_dir.mkdir(parents=True, exist_ok=True)
        for spec in specs:
            launcher = launcher_dir / f"launch_{spec['id']}.sh"
            launcher.write_text(_launcher(plan_sha, spec, train, evaluation), encoding="utf-8"); launcher.chmod(launcher.stat().st_mode | 0o111)
        print(json.dumps({"status": "generated_no_training_started", "plan": str(plan_path), "plan_sha256": plan_sha, "launchers": str(launcher_dir), "experiments": [spec["id"] for spec in specs]}, ensure_ascii=False))
        return 0
    except (OSError, ValueError, json.JSONDecodeError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
